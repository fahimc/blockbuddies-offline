import type { JobTaskVariant, Vec3 } from '../game/types'

type Choice = [id: string, label: string]

function challenge(
  id: string,
  orderLabel: string,
  prompt: string,
  choices: Choice[],
  correctOptionId: string,
  successLine: string,
  details: { customerName?: string; position?: Vec3 } = {},
): JobTaskVariant {
  return {
    id,
    orderLabel,
    prompt,
    options: choices.map(([optionId, label]) => ({ id: optionId, label })),
    correctOptionId,
    successLine,
    ...details,
  }
}
